"""Text of a .pptx as Markdown: one section per slide with text, tables and notes."""

from __future__ import annotations

import io
import re
from dataclasses import dataclass, field

import yaml
from pptx import Presentation
from pptx.enum.shapes import MSO_SHAPE_TYPE, PP_PLACEHOLDER

BODY_PLACEHOLDERS = {PP_PLACEHOLDER.BODY, PP_PLACEHOLDER.OBJECT}
TITLE_PLACEHOLDERS = {PP_PLACEHOLDER.TITLE, PP_PLACEHOLDER.CENTER_TITLE}
SKIP_PLACEHOLDERS = {
    PP_PLACEHOLDER.DATE,
    PP_PLACEHOLDER.FOOTER,
    PP_PLACEHOLDER.SLIDE_NUMBER,
    PP_PLACEHOLDER.HEADER,
}


class ExtractError(Exception):
    pass


@dataclass
class Slide:
    number: int
    title: str = ""
    blocks: list[str] = field(default_factory=list)
    notes: str = ""
    hidden: bool = False


def extract(data: bytes) -> list[Slide]:
    try:
        deck = Presentation(io.BytesIO(data))
    except Exception as exc:  # zipfile, lxml and python-pptx raise many kinds
        raise ExtractError("not a readable .pptx (password-protected or damaged?)") from exc
    try:
        return _slides(deck)
    except Exception as exc:  # pragma: no cover - unusual files
        raise ExtractError(f"could not read the slides ({type(exc).__name__})") from exc


def _slides(deck) -> list[Slide]:
    slides: list[Slide] = []
    for number, s in enumerate(deck.slides, start=1):
        slide = Slide(number=number, hidden=s._element.get("show") == "0")
        for shape in _ordered(s.shapes):
            kind = _placeholder(shape)
            if kind in SKIP_PLACEHOLDERS:
                continue
            if kind in TITLE_PLACEHOLDERS and not slide.title:
                slide.title = _clean(shape.text_frame.text)
                continue
            block = _block(shape, bulleted=kind in BODY_PLACEHOLDERS)
            if block:
                slide.blocks.append(block)
        if s.has_notes_slide and s.notes_slide.notes_text_frame is not None:
            slide.notes = s.notes_slide.notes_text_frame.text.strip()
        slides.append(slide)
    return slides


def _placeholder(shape):
    if not shape.is_placeholder:
        return None
    try:
        return shape.placeholder_format.type
    except ValueError:  # pragma: no cover - unknown placeholder
        return None


def _ordered(shapes):
    """Reading order: top to bottom, then left to right; groups are flattened."""
    flat = []
    for shape in shapes:
        if shape.shape_type == MSO_SHAPE_TYPE.GROUP:
            flat += _ordered(shape.shapes)
        else:
            flat.append(shape)
    return sorted(flat, key=lambda sh: (sh.top or 0, sh.left or 0))


def _block(shape, bulleted: bool) -> str:
    if getattr(shape, "has_table", False) and shape.has_table:
        return _table(shape.table)
    if not getattr(shape, "has_text_frame", False) or not shape.has_text_frame:
        return ""
    paragraphs = [(p.level, _clean(_text(p))) for p in shape.text_frame.paragraphs]
    paragraphs = [(level, text) for level, text in paragraphs if text]
    if not paragraphs:
        return ""
    if bulleted or len(paragraphs) > 1:
        return "\n".join(f"{'  ' * level}- {_escape(text)}" for level, text in paragraphs)
    return _escape(paragraphs[0][1])


def _text(paragraph) -> str:
    return "".join(run.text for run in paragraph.runs) or paragraph.text


def _table(table) -> str:
    rows = [[_clean(cell.text).replace("|", "\\|") for cell in row.cells] for row in table.rows]
    if not rows:
        return ""
    width = max(len(r) for r in rows)
    rows = [r + [""] * (width - len(r)) for r in rows]
    lines = ["| " + " | ".join(rows[0]) + " |", "|" + " --- |" * width]
    lines += ["| " + " | ".join(r) + " |" for r in rows[1:]]
    return "\n".join(lines)


def _clean(text: str) -> str:
    return re.sub(r"\s+", " ", text.replace("\x0b", " ")).strip()


def _escape(line: str) -> str:
    """Keep slide text from turning into Markdown headings, quotes or rules."""
    return "\\" + line if re.match(r"^(#|>|---|\*\*\*|=+$)", line) else line


# -- note rendering ----------------------------------------------------------------

NOTICE = (
    "> Mirror of [{title}]({url}) in OneDrive, generated by LifeOS. Edit the presentation"
    " in PowerPoint; changes here are overwritten on the next sync."
)


def render(meta: dict, slides: list[Slide]) -> str:
    front = {
        "type": "presentation",
        "source": "onedrive",
        "title": meta["title"],
        "url": meta["url"],
        "onedrive_path": meta["path"],
        "drive_item_id": meta["id"],
        "modified": meta["modified"],
        "slides": len(slides),
        "mirror": True,
    }
    out = ["---", yaml.safe_dump(front, sort_keys=False, allow_unicode=True).strip(), "---", ""]
    out.append(f"# {meta['title']}")
    out.append("")
    out.append(NOTICE.format(title=meta["title"].replace("]", "\\]"), url=_link(meta["url"])))
    for slide in slides:
        heading = f"## Slide {slide.number}"
        if slide.title:
            heading += f" · {slide.title}"
        if slide.hidden:
            heading += " (hidden)"
        out += ["", heading]
        for block in slide.blocks:
            out += ["", block]
        if slide.notes:
            notes = slide.notes.splitlines()
            out += ["", "> **Notes:** " + notes[0]] + [f"> {line}" for line in notes[1:]]
    return "\n".join(out).rstrip() + "\n"


def _link(url: str) -> str:
    return f"<{url}>" if any(c in url for c in " ()") else url


def mark_deleted(content: str) -> str:
    """Flag a mirror whose presentation is gone; the text stays for reference."""
    if not content.startswith("---\n"):
        return content
    end = content.find("\n---\n", 4)
    if end < 0:
        return content
    front = yaml.safe_load(content[4:end]) or {}
    if front.get("status") == "deleted":
        return content
    front["status"] = "deleted"
    head = yaml.safe_dump(front, sort_keys=False, allow_unicode=True).strip()
    return f"---\n{head}\n---\n" + content[end + 5 :]


def front_matter(content: str) -> dict:
    if not content.startswith("---\n"):
        return {}
    end = content.find("\n---\n", 4)
    if end < 0:
        return {}
    try:
        data = yaml.safe_load(content[4:end])
    except yaml.YAMLError:
        return {}
    return data if isinstance(data, dict) else {}
